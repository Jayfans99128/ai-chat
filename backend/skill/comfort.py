"""
AI-Girlfriend-Agent — 安慰陪伴技能

当检测到用户情绪低落、焦虑或疲惫时，提供情感支持和安慰。
"""

import logging
import random

logger = logging.getLogger("skill_comfort")

# 安慰语录（根据情绪分类）
COMFORT_MESSAGES = {
    "sad": [
        "别难过啦，我在这里陪着你呢~",
        "想哭就哭出来吧，有时候哭一场会好很多。",
        "不管发生什么事，我都会站在你这边。",
        "抱抱你~一切都会好起来的！",
        "你不是一个人，有我在呢。",
    ],
    "angry": [
        "消消气，深呼吸~生气对身体不好哦。",
        "我理解你为什么会生气，换作是我可能也会这样。",
        "先冷静一下，我们慢慢想办法。",
        "那个人/那件事不值得你生这么大的气~",
    ],
    "tired": [
        "辛苦啦~今天真的累着了吧？",
        "累了就好好休息，什么都不用想。",
        "你已经做得很好了，给自己一点休息的时间吧。",
        "要不要我给你泡杯茶？虽然我只能在想象中给你泡啦~",
    ],
    "anxious": [
        "别担心，慢慢来，一件一件处理就好。",
        "你已经很努力了，相信自己！",
        "深呼吸，冷静一下。事情没有你想的那么糟糕。",
        "不管结果如何，我都会支持你的。",
    ],
    "normal": [
        "不管什么时候，我都在这里陪着你~",
        "有什么想说的都可以告诉我哦。",
        "今天也要开心地度过呀！",
    ],
}


def get_comfort_message(emotion: str) -> str:
    """根据情绪返回合适的安慰话"""
    messages = COMFORT_MESSAGES.get(emotion, COMFORT_MESSAGES["normal"])
    return random.choice(messages)


def get_deep_comfort() -> str:
    """深度安慰 — 用于用户情绪非常低落时"""
    deep_messages = [
        "我知道现在可能很难受，但请记住，这个世界上总有人在关心你。",
        "每个人都会有低谷的时候，这不是你的错。给自己一些时间，慢慢来。",
        "你比你想象的更坚强。以前那么多困难都挺过来了，这次也一定可以。",
        "有时候停下来休息也是一种前进。不要给自己太大压力。",
    ]
    return random.choice(deep_messages)